const CATEGORIES = [
  "All categories",
  "Translation",
  "Recording",
  "Policy",
  "Support",
  "PSL dictionary",
];

const STATUSES = ["All statuses", "Published", "Draft"];

const EMPTY_FORM = {
  title: "",
  category: "Translation",
  status: "Draft",
  description: "",
};

function KnowledgeBase() {
  const [articles, setArticles] = useState(INITIAL_ARTICLES);
  const [search, setSearch] = useState("");
  const [category, setCategory] = useState("All categories");
  const [status, setStatus] = useState("All statuses");
  const [sortOrder, setSortOrder] = useState("recent");
  const [currentPage, setCurrentPage] = useState(1);

  const [modalOpen, setModalOpen] = useState(false);
  const [manageArticle, setManageArticle] = useState(null);
  const [editingArticle, setEditingArticle] = useState(null);
  const [formData, setFormData] = useState(EMPTY_FORM);

  const articlesPerPage = 6;

  const filteredArticles = useMemo(() => {
    const result = articles.filter((article) => {
      const searchText = search.toLowerCase();

      const matchesSearch =
        article.title.toLowerCase().includes(searchText) ||
        article.category.toLowerCase().includes(searchText) ||
        article.description.toLowerCase().includes(searchText);

      const matchesCategory =
        category === "All categories" || article.category === category;

      const matchesStatus =
        status === "All statuses" || article.status === status;

      return matchesSearch && matchesCategory && matchesStatus;
    });

    return [...result].sort((a, b) => {
      if (sortOrder === "oldest") {
        return a.id - b.id;
      }

      if (sortOrder === "alphabetical") {
        return a.title.localeCompare(b.title);
      }

      return b.id - a.id;
    });
  }, [articles, search, category, status, sortOrder]);

  const totalPages = Math.max(
    1,
    Math.ceil(filteredArticles.length / articlesPerPage)
  );

  const visibleArticles = filteredArticles.slice(
    (currentPage - 1) * articlesPerPage,
    currentPage * articlesPerPage
  );

  const resetPage = () => setCurrentPage(1);

  const openAddModal = () => {
    setEditingArticle(null);
    setFormData(EMPTY_FORM);
    setModalOpen(true);
  };

  const openEditModal = (article) => {
    setEditingArticle(article);
    setFormData({
      title: article.title,
      category: article.category,
      status: article.status,
      description: article.description,
    });
    setManageArticle(null);
    setModalOpen(true);
  };

  const closeModal = () => {
    setModalOpen(false);
    setEditingArticle(null);
    setFormData(EMPTY_FORM);
  };

  const handleFormChange = (event) => {
    const { name, value } = event.target;

    setFormData((previous) => ({
      ...previous,
      [name]: value,
    }));
  };

  const handleSave = (event) => {
    event.preventDefault();

    if (editingArticle) {
      setArticles((previous) =>
        previous.map((article) =>
          article.id === editingArticle.id
            ? { ...article, ...formData, date: "09 Nov 2026" }
            : article
        )
      );
    } else {
      const newArticle = {
        id: Date.now(),
        ...formData,
        date: "09 Nov 2026",
      };

      setArticles((previous) => [newArticle, ...previous]);
      setCategory("All categories");
      setStatus("All statuses");
      setSearch("");
    }

    resetPage();
    closeModal();
  };

  const handleStatusChange = (article) => {
    setArticles((previous) =>
      previous.map((item) =>
        item.id === article.id
          ? {
              ...item,
              status: item.status === "Published" ? "Draft" : "Published",
              date: "09 Nov 2026",
            }
          : item
      )
    );

    setManageArticle(null);
  };

  const handleDelete = (id) => {
    const confirmed = window.confirm(
      "Are you sure you want to delete this article?"
    );

    if (!confirmed) return;

    const remainingCount = filteredArticles.length - 1;

    setArticles((previous) =>
      previous.filter((article) => article.id !== id)
    );

    setCurrentPage((page) =>
      Math.min(
        page,
        Math.max(1, Math.ceil(remainingCount / articlesPerPage))
      )
    );

    setManageArticle(null);
  };

  const handleSearch = (event) => {
    setSearch(event.target.value);
    resetPage();
  };

  const handleCategory = (event) => {
    setCategory(event.target.value);
    resetPage();
  };

  const handleStatus = (event) => {
    setStatus(event.target.value);
    resetPage();
  };

  const handleSort = (event) => {
    setSortOrder(event.target.value);
    resetPage();
  };

  return (
    <div className="knowledge-page">
      <div className="knowledge-heading">
        <div>
          <h1>Knowledge base</h1>
          <p>
            Maintain trusted learning resources and platform guidance. -
            Example data
          </p>
        </div>
      </div>

      <div className="knowledge-toolbar">
        <div className="knowledge-search">
          <span>⌕</span>
          <input
            type="text"
            placeholder="Search articles, categories, or keywords"
            value={search}
            onChange={handleSearch}
          />
        </div>

        <select
          value={category}
          onChange={handleCategory}
          aria-label="Filter by category"
        >
          {CATEGORIES.map((item) => (
            <option key={item} value={item}>
              {item}
            </option>
          ))}
        </select>

        <select
          value={status}
          onChange={handleStatus}
          aria-label="Filter by status"
        >
          {STATUSES.map((item) => (
            <option key={item} value={item}>
              {item}
            </option>
          ))}
        </select>

        <button
          className="knowledge-add-btn"
          onClick={openAddModal}
        >
          + Add article
        </button>
      </div>

      <div className="knowledge-list-info">
        <span>{filteredArticles.length} articles · Example data</span>

        <select
          value={sortOrder}
          onChange={handleSort}
          aria-label="Sort articles"
          className="knowledge-sort"
        >
          <option value="recent">Updated recently</option>
          <option value="oldest">Oldest first</option>
          <option value="alphabetical">Alphabetical</option>
        </select>
      </div>

      <div className="knowledge-article-list">
        {visibleArticles.length > 0 ? (
          visibleArticles.map((article) => (
            <article className="knowledge-article" key={article.id}>
              <div className="knowledge-article-info">
                <h3>{article.title}</h3>

                <div className="knowledge-article-meta">
                  <span className="knowledge-category">
                    {article.category}
                  </span>
                  <span>Updated {article.date}</span>
                </div>
              </div>

              <div className="knowledge-article-actions">
                <span
                  className={`knowledge-status ${article.status.toLowerCase()}`}
                >
                  {article.status}
                </span>

                <button
                  className="knowledge-action-btn edit"
                  onClick={() => openEditModal(article)}
                >
                  <span>✎</span> Edit
                </button>

                <button
                  className="knowledge-action-btn"
                  onClick={() => setManageArticle(article)}
                >
                  ··· Manage
                </button>
              </div>
            </article>
          ))
        ) : (
          <div className="knowledge-empty">
            No articles found. Try changing your search or filters.
          </div>
        )}
      </div>

      <div className="knowledge-footer">
        <span>
          Showing {filteredArticles.length === 0 ? 0 : (currentPage - 1) * articlesPerPage + 1}
          –
          {Math.min(currentPage * articlesPerPage, filteredArticles.length)} of{" "}
          {filteredArticles.length} articles
        </span>

        <div className="knowledge-pagination">
          <button
            disabled={currentPage === 1}
            onClick={() => setCurrentPage((page) => page - 1)}
          >
            ‹
          </button>

          {Array.from({ length: totalPages }, (_, index) => index + 1)
            .slice(0, 5)
            .map((page) => (
              <button
                key={page}
                className={currentPage === page ? "active" : ""}
                onClick={() => setCurrentPage(page)}
              >
                {page}
              </button>
            ))}

          <button
            disabled={currentPage === totalPages}
            onClick={() => setCurrentPage((page) => page + 1)}
          >
            ›
          </button>
        </div>
      </div>

      {modalOpen && (
        <div className="knowledge-modal-overlay" onClick={closeModal}>
          <div
            className="knowledge-modal"
            onClick={(event) => event.stopPropagation()}
          >
            <div className="knowledge-modal-heading">
              <h2>{editingArticle ? "Edit article" : "Add article"}</h2>
              <button type="button" onClick={closeModal}>
                ×
              </button>
            </div>

            <form onSubmit={handleSave}>
              <label htmlFor="article-title">Article title</label>
              <input
                id="article-title"
                name="title"
                value={formData.title}
                onChange={handleFormChange}
                placeholder="Enter article title"
                required
              />

              <label htmlFor="article-category">Category</label>
              <select
                id="article-category"
                name="category"
                value={formData.category}
                onChange={handleFormChange}
              >
                {CATEGORIES.slice(1).map((item) => (
                  <option key={item} value={item}>
                    {item}
                  </option>
                ))}
              </select>

              <label htmlFor="article-status">Status</label>
              <select
                id="article-status"
                name="status"
                value={formData.status}
                onChange={handleFormChange}
              >
                <option value="Draft">Draft</option>
                <option value="Published">Published</option>
              </select>

              <label htmlFor="article-description">Article content</label>
              <textarea
                id="article-description"
                name="description"
                value={formData.description}
                onChange={handleFormChange}
                placeholder="Write your article content..."
                rows="5"
                required
              />

              <div className="knowledge-modal-actions">
                <button
                  type="button"
                  className="knowledge-cancel-btn"
                  onClick={closeModal}
                >
                  Cancel
                </button>

                <button type="submit" className="knowledge-add-btn">
                  Save article
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {manageArticle && (
        <div
          className="knowledge-modal-overlay"
          onClick={() => setManageArticle(null)}
        >
          <div
            className="knowledge-modal knowledge-manage-modal"
            onClick={(event) => event.stopPropagation()}
          >
            <div className="knowledge-modal-heading">
              <h2>Manage article</h2>
              <button
                type="button"
                onClick={() => setManageArticle(null)}
              >
                ×
              </button>
            </div>

            <h3>{manageArticle.title}</h3>
            <p>{manageArticle.description}</p>

            <div className="knowledge-manage-details">
              <span>Category: {manageArticle.category}</span>
              <span>Status: {manageArticle.status}</span>
              <span>Updated: {manageArticle.date}</span>
            </div>

            <div className="knowledge-modal-actions">
              <button
                className="knowledge-cancel-btn"
                onClick={() => handleDelete(manageArticle.id)}
              >
                Delete
              </button>

              <button
                className="knowledge-cancel-btn"
                onClick={() => handleStatusChange(manageArticle)}
              >
                {manageArticle.status === "Published"
                  ? "Move to draft"
                  : "Publish"}
              </button>

              <button
                className="knowledge-add-btn"
                onClick={() => openEditModal(manageArticle)}
              >
                Edit article
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

export default KnowledgeBase;
